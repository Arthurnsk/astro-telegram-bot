from datetime import datetime


def get_number():
    # Получаем текущую дату в формате ДДММГГГГ
    today = datetime.now().strftime("%d%m%Y")

    # Считаем сумму цифр
    num = sum(int(i) for i in today)

    # Сокращаем до однозначного (от 1 до 9)
    while num > 9:
        num = sum(int(i) for i in str(num))

    meanings = {
        1: "новые начинания и лидерство",
        2: "гармония, партнерство и баланс",
        3: "творчество, самовыражение и рост",
        4: "стабильность, порядок и упорный труд",
        5: "перемены, свобода и приключения",
        6: "ответственность, семья и забота",
        7: "духовный поиск, мудрость и анализ",
        8: "успех, власть и материальные достижения",
        9: "завершение этапа, мудрость и гуманизм"
    }

    return num, meanings[num]